def write_repo_hygiene(dest: Path) -> None:
    if not (dest / ".gitignore").is_file():
        (dest / ".gitignore").write_text(DEFAULT_GITIGNORE)
    gh_dir = dest / ".github"
    gh_dir.mkdir(parents=True, exist_ok=True)
    if not (gh_dir / "CODEOWNERS").is_file():
        (gh_dir / "CODEOWNERS").write_text(DEFAULT_CODEOWNERS)
    pr = gh_dir / "pull_request_template.md"
    if not pr.is_file():
        pr.write_text(
            "## Linear\n\n## What changed\n\n## OpenSpec\n\n"
            "Path, or none for a bug that did not need a design choice.\n\n"
            "## Commands run\n\n## Risk\n\n"
            "- [ ] This pull request does not mix product code with infra, workflows, or service.yaml\n"
        )
    openspec_dir = dest / "openspec"
    openspec_dir.mkdir(parents=True, exist_ok=True)
    if not any(openspec_dir.iterdir()):
        (openspec_dir / ".gitkeep").write_text("")
    scripts_dir = dest / "scripts"
    scripts_dir.mkdir(parents=True, exist_ok=True)
    # Deploy workflows check out the app, then run these files from that
    # checkout. They are not read from sdlc-resources at deploy time.
    for filename in (
        "render_tfvars.py",
        "yaml_subset.py",
        "check_secret_versions.py",
        "check_firestore.py",
    ):
        shutil.copy2(ROOT / "scripts" / filename, scripts_dir / filename)


def _load_and_normalize(manifest_path: Path) -> tuple[dict, dict, list[dict]]:
    raw = load(manifest_path)
    errors = check(raw)
    if errors:
        raise SystemExit("\n".join(errors))
    app = normalize(raw)
    mapping = load(ROOT / "mapping.yaml")
    return app, mapping, app["components"]


def phase_init_runtime(manifest_path: Path, dest: Path, overwrite: bool = False) -> None:
    app, mapping, components = _load_and_normalize(manifest_path)
    dest.mkdir(parents=True, exist_ok=True)
    if manifest_path.resolve() != (dest / "service.yaml").resolve():
        shutil.copy2(manifest_path, dest / "service.yaml")
    write_repo_hygiene(dest)
    write_githooks(dest)
    write_devcontainer(dest)
    for component in components:
        comp_dir = component_dir_for(dest, component)
        if comp_dir.resolve() != dest.resolve():
            copy_skeleton(mapping, component, comp_dir, overwrite=overwrite)
            write_component_manifest(app, component, comp_dir)
        else:
            copy_skeleton(mapping, component, comp_dir, overwrite=False)
    write_local_dev_files(app, components, dest)


def phase_add_data(manifest_path: Path, dest: Path) -> None:
    app, mapping, components = _load_and_normalize(manifest_path)
    for component in components:
        comp_dir = component_dir_for(dest, component)
        comp_dir.mkdir(parents=True, exist_ok=True)
        apply_data_layer(mapping, component, comp_dir)
        if comp_dir.resolve() != dest.resolve():
            write_component_manifest(app, component, comp_dir)


def phase_add_tests(manifest_path: Path, dest: Path) -> None:
    _, _, components = _load_and_normalize(manifest_path)
    for component in components:
        comp_dir = component_dir_for(dest, component)
        comp_dir.mkdir(parents=True, exist_ok=True)
        apply_test_layer(component, comp_dir)


def phase_sync_infra(manifest_path: Path, dest: Path, ci_only: bool = False) -> None:
    app, mapping, components = _load_and_normalize(manifest_path)
    dest.mkdir(parents=True, exist_ok=True)
    if manifest_path.resolve() != (dest / "service.yaml").resolve():
        shutil.copy2(manifest_path, dest / "service.yaml")
    write_repo_hygiene(dest)
    write_githooks(dest)
    write_devcontainer(dest)
    _, rules = selected(mapping, components)
    write_bundle(dest, rules)
    if not ci_only:
        for component in components:
            comp_dir = component_dir_for(dest, component)
            comp_dir.mkdir(parents=True, exist_ok=True)
            sync_runtime_sdk(component, comp_dir)
            if comp_dir.resolve() != dest.resolve():
                write_component_manifest(app, component, comp_dir)
            write_infra(mapping, app, component, comp_dir)
    else:
        for component in components:
            comp_dir = component_dir_for(dest, component)
            if comp_dir.is_dir():
                sync_runtime_sdk(component, comp_dir)
    write_workflows(mapping, components, dest, include_deploy=not ci_only)
    write_local_dev_files(app, components, dest, build_images=not ci_only)
    write_bind_script(app, dest)
    write_readme(app, components, dest)


def generate(manifest_path: Path, dest: Path) -> None:
    if dest.exists() and any(dest.iterdir()):
        raise SystemExit(f"{dest} is not empty")
    phase_init_runtime(manifest_path, dest, overwrite=True)
    phase_add_data(manifest_path, dest)
    phase_add_tests(manifest_path, dest)
    phase_sync_infra(manifest_path, dest)


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("dest", type=Path)
    args = parser.parse_args(argv[1:])
    generate(args.manifest, args.dest)
    print(args.dest)
    return 0


