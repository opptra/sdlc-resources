def load(path: Path) -> dict:
    return parse(path.read_text())


def selected(mapping: dict, components: list[dict]) -> tuple[list[str], list[str]]:
    capabilities: list[str] = []
    rules = ["always"]
    for component in components:
        for part in component["parts"]:
            spec = mapping["parts"][part]
            for name in spec["capabilities"]:
                if name not in capabilities:
                    capabilities.append(name)
            for name in spec["rules"]:
                if name not in rules:
                    rules.append(name)
        db = component.get("database", "none")
        if db == "postgres":
            if "database" not in rules:
                rules.append("database")
            if "terraform" not in rules:
                rules.append("terraform")
            if "terraform-plan" not in capabilities:
                capabilities.append("terraform-plan")
        elif db == "firestore":
            if "firestore" not in rules:
                rules.append("firestore")
            if "terraform" not in rules:
                rules.append("terraform")
            if "terraform-plan" not in capabilities:
                capabilities.append("terraform-plan")
        elif db == "bigquery" or component.get("bigquery"):
            if "bigquery" not in rules:
                rules.append("bigquery")
        if (
            component.get("bucket", "none") == "private"
            or component.get("queue")
            or component.get("secrets")
            or component.get("alerts")
            or component.get("jobs")
            or component.get("receiver")
        ):
            if "terraform" not in rules:
                rules.append("terraform")
            if "terraform-plan" not in capabilities and component.get("archetype") != "config-only":
                capabilities.append("terraform-plan")
    return capabilities, rules


def component_dir_for(dest: Path, component: dict) -> Path:
    custom = component.get("path")
    if custom:
        return dest if custom == "." else (dest / str(custom))
    return dest / "components" / component["name"]


def copy_skeleton(mapping: dict, component: dict, dest: Path, overwrite: bool = True) -> None:
    dest.mkdir(parents=True, exist_ok=True)
    parts = set(component["parts"])
    for part in component["parts"]:
        source = ROOT / mapping["parts"][part]["skeleton"]
        if part == "ui":
            ui_dest = dest / "frontend"
            if not ui_dest.exists() or overwrite:
                if ui_dest.exists():
                    shutil.rmtree(ui_dest)
                shutil.copytree(source, ui_dest)
            else:
                _copy_missing_tree(source, ui_dest)
            continue
        for item in source.iterdir():
            target = dest / item.name
            if item.is_dir():
                if target.exists() and overwrite:
                    shutil.rmtree(target)
                if not target.exists():
                    shutil.copytree(item, target)
                else:
                    _copy_missing_tree(item, target)
            else:
                if not target.exists() or overwrite:
                    shutil.copy2(item, target)
    if parts & {"api", "job", "worker"}:
        common_src = ROOT / "skeletons" / "_common"
        if common_src.is_dir():
            _copy_missing_tree(common_src, dest)
        sync_runtime_sdk(component, dest, force=True)
    if "api" in parts:
        dockerfile = "Dockerfile.with-ui" if "ui" in parts else "Dockerfile.api-only"
        if (dest / dockerfile).is_file():
            (dest / "Dockerfile").write_text((dest / dockerfile).read_text())
        (dest / "Dockerfile.with-ui").unlink(missing_ok=True)
        (dest / "Dockerfile.api-only").unlink(missing_ok=True)

    jobs = component.get("jobs")
    if isinstance(jobs, list) and jobs:
        jobs_map = {}
        jobs_pkg = dest / "backend" / "app" / "jobs"
        jobs_pkg.mkdir(parents=True, exist_ok=True)
        if not (jobs_pkg / "__init__.py").exists():
            (jobs_pkg / "__init__.py").write_text("")
        for job in jobs:
            jname = str(job["name"])
            cmd_str = str(job.get("command", ""))
            if cmd_str.startswith("python -m app.jobs."):
                py_mod = cmd_str.split("python -m app.jobs.", 1)[1].split()[0]
            else:
                py_mod = jname.replace("-", "_")
            jobs_map[jname] = {
                "enabled": bool(job.get("enabled", True)),
                "command": str(job.get("command", f"python -m app.jobs.{py_mod}")),
                "schedules": list(job.get("schedules", [])),
                "timezone": str(job.get("timezone", "Asia/Kolkata")),
                "timeout_seconds": int(job.get("timeout_seconds", 1800)),
                "memory": str(job.get("memory", "1Gi")),
                "secrets": list(job.get("secrets", [])),
            }
            mod_file = jobs_pkg / f"{py_mod}.py"
            if not mod_file.exists():
                mod_file.write_text(
                    f'"""Entrypoint for job {jname}."""\n\n'
                    "from __future__ import annotations\n\n"
                    "from app.runner import run_job\n\n\n"
                    "def handle(mode: str = 'sweep', ticket_id: int | None = None) -> str:\n"
                    "    return 'ok'\n\n\n"
                    "def main() -> int:\n"
                    f"    code, status = run_job({jname!r}, lambda: handle())\n"
                    "    print(status)\n"
                    "    return code\n\n\n"
                    "if __name__ == '__main__':\n"
                    "    raise SystemExit(main())\n"
                )
        cfg_dir = dest / "config"
        cfg_dir.mkdir(parents=True, exist_ok=True)
        cfg_data = {
            "defaults": {
                "region": str(component.get("region", "asia-south1")),
                "timezone": "Asia/Kolkata",
            },
            "jobs": jobs_map,
        }
        (cfg_dir / "jobs.yaml").write_text(dump(cfg_data))


def apply_data_layer(mapping: dict, component: dict, dest: Path) -> None:
    if component.get("archetype") == "config-only":
        return
    db = component.get("database", "none")
    bucket = component.get("bucket", "none")
    queue = component.get("queue")
    secrets = component.get("secrets", [])

    packages: list[str] = []
    cloud_caps = mapping.get("cloud_capabilities", {})
    if db in {"postgres", "firestore", "bigquery"}:
        packages.extend(cloud_caps.get(db, {}).get("packages", []))
    if component.get("bigquery") and db != "bigquery":
        packages.extend(cloud_caps.get("bigquery", {}).get("packages", []))
    if bucket == "private":
        packages.extend(cloud_caps.get("bucket", {}).get("packages", []))
    if queue:
        packages.extend(cloud_caps.get("queue", {}).get("packages", []))
    if secrets:
        packages.extend(cloud_caps.get("secrets", {}).get("packages", []))
    if component.get("receiver"):
        for pkg in ("fastapi>=0.115", "uvicorn>=0.32"):
            if pkg not in packages:
                packages.append(pkg)

    if db == "postgres":
        src = ROOT / "skeletons" / "data-postgres"
        if src.exists():
            _copy_missing_tree(src, dest)
    if db == "firestore" or bucket == "private":
        src = ROOT / "skeletons" / "data-firestore"
        if src.exists():
            _copy_missing_tree(src, dest)

    pyproject = dest / "pyproject.toml"
    if pyproject.is_file() and packages:
        _ensure_pyproject_deps(pyproject, packages)


