#!/usr/bin/env python3
"""Create an app directory from service.yaml.

The yaml holds facts. mapping.yaml decides the files, the workflows, and the rules.
Generated workflow files are stamped. Edit service.yaml and run this again only
for a new app. Later edits happen in the app repository.
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from build_rules import write_bundle
from check_manifest import check
from yaml_subset import parse

ROOT = Path(__file__).resolve().parents[1]
STAMP = "generated by opptra/sdlc scripts/generate.py version 1. Edit service.yaml and regenerate only for a new app."


def load(path: Path):
    return parse(path.read_text())


def selected(mapping: dict, components: list[dict]) -> tuple[list[str], list[str]]:
    capabilities: list[str] = []
    rules = ["always"]
    for component in components:
        for part in component["parts"]:
            spec = mapping["parts"][part]
            for name in spec["capabilities"]:
                if name not in capabilities:
                    capabilities.append(name)
            for name in spec["rules"]:
                if name not in rules:
                    rules.append(name)
    return capabilities, rules


def copy_skeleton(mapping: dict, component: dict, dest: Path) -> None:
    if dest.exists():
        shutil.rmtree(dest)
    dest.mkdir(parents=True)
    parts = set(component["parts"])
    for part in component["parts"]:
        source = ROOT / mapping["parts"][part]["skeleton"]
        if part == "ui":
            shutil.copytree(source, dest / "frontend")
            continue
        for item in source.iterdir():
            target = dest / item.name
            if item.is_dir():
                if target.exists():
                    shutil.rmtree(target)
                shutil.copytree(item, target)
            else:
                shutil.copy2(item, target)
    if "api" in parts:
        dockerfile = "Dockerfile.with-ui" if "ui" in parts else "Dockerfile.api-only"
        (dest / "Dockerfile").write_text((dest / dockerfile).read_text())
        (dest / "Dockerfile.with-ui").unlink(missing_ok=True)
        (dest / "Dockerfile.api-only").unlink(missing_ok=True)


def write_component_manifest(app: dict, component: dict, dest: Path) -> None:
    parts = ", ".join(component["parts"])
    text = (
        f"# {STAMP}\n"
        f"name: {component['name']}\n"
        f"archetype: {component['archetype']}\n"
        f"prod_project: {app['prod_project']}\n"
        f"region: {app['region']}\n"
        f"auth: {component['auth']}\n"
        f"parts: [{parts}]\n"
    )
    (dest / "service.yaml").write_text(text)


def write_infra(mapping: dict, app: dict, component: dict, dest: Path) -> None:
    module = None
    for part in component["parts"]:
        module = mapping["parts"][part].get("terraform_module") or module
    if not module:
        return
    infra = dest / "infra"
    infra.mkdir()
    ref = mapping["ref"]
    repo = mapping["repo"]
    (infra / "versions.tf").write_text(
        """terraform {
  required_version = ">= 1.9.0"

  required_providers {
    google = {
      source  = "hashicorp/google"
      version = ">= 6.0.0, < 8.0.0"
    }
  }

  backend "gcs" {}
}

provider "google" {
  project = var.project_id
  region  = var.region
}
"""
    )
    variables = ["project_id", "region", "name", "environment", "image"]
    if module == "cloud-run-service":
        variables.append("auth")
    body = "\n".join(f'variable "{name}" {{\n  type = string\n}}\n' for name in variables)
    (infra / "variables.tf").write_text(body)
    auth_line = '  auth        = var.auth\n' if module == "cloud-run-service" else ""
    (infra / "main.tf").write_text(
        f"""# {STAMP}
module "service" {{
  source = "git::https://github.com/{repo}.git//modules/{module}?ref={ref}"

  project_id  = var.project_id
  region      = var.region
  name        = var.name
  environment = var.environment
  image       = var.image
{auth_line}}}
"""
    )
    output = 'output "uri" {\n  value = module.service.uri\n}\n'
    if module == "cloud-run-job":
        output = 'output "name" {\n  value = module.service.name\n}\n'
    (infra / "outputs.tf").write_text(output)
    del app


def workflow_call(job_id: str, workflow: str, repo: str, ref: str, arguments: dict[str, str]) -> str:
    lines = [f"  {job_id}:", f"    uses: {repo}/.github/workflows/{workflow}@{ref}"]
    if arguments:
        lines.append("    with:")
        for key, value in arguments.items():
            lines.append(f"      {key}: {value}")
    return "\n".join(lines)


def write_workflows(mapping: dict, components: list[dict], dest: Path) -> None:
    ref = mapping["ref"]
    workflows = dest / ".github" / "workflows"
    workflows.mkdir(parents=True)
    ci_jobs = []
    plan_jobs = []
    deploy_staging = []
    deploy_production = []
    for component in components:
        caps, _ = selected(mapping, [component])
        base = component["name"]
        for capability in caps:
            spec = mapping["capabilities"][capability]
            directory = spec["directory"]
            if directory == "component":
                path = f"components/{base}"
            elif directory == "frontend":
                path = f"components/{base}/frontend"
            else:
                path = "."
            job_id = f"{capability}-{base}".replace("_", "-")
            args = {"working_directory": path}
            if capability in {"terraform-plan", "deploy-cloud-run", "deploy-job", "deploy-worker"}:
                args["manifest"] = f"components/{base}/service.yaml"
            if capability == "terraform-plan":
                plan_jobs.append((job_id, spec["workflow"], args))
            elif capability.startswith("deploy-"):
                deploy_staging.append((job_id, spec["workflow"], {**args, "environment": "staging"}))
                deploy_production.append(
                    (job_id, spec["workflow"], {**args, "environment": "prod"})
                )
            else:
                ci_jobs.append((job_id, spec["workflow"], args))
    repo = mapping["repo"]
    write_gate(workflows / "ci.yml", "ci", ci_jobs, repo, ref, """on:
  pull_request:
""")
    if plan_jobs:
        write_plan(workflows / "plan.yml", plan_jobs, repo, ref)
    if deploy_staging:
        write_deploy(workflows / "deploy-staging.yml", "staging", deploy_staging, repo, ref)
        write_deploy(workflows / "deploy-production.yml", "production", deploy_production, repo, ref)


def write_gate(path: Path, name: str, jobs: list, repo: str, ref: str, trigger: str) -> None:
    body = [f"# {STAMP}", f"name: {name}", trigger, "permissions:", "  contents: read", "jobs:"]
    ids = []
    for job_id, workflow, args in jobs:
        ids.append(job_id)
        body.append(workflow_call(job_id, workflow, repo, ref, args))
    needs = ", ".join(ids) if ids else ""
    body.append("  ci:")
    if needs:
        body.append(f"    needs: [{needs}]")
    body.append("    runs-on: ubuntu-latest")
    body.append("    steps:")
    body.append("      - run: echo capabilities passed")
    path.write_text("\n".join(body) + "\n")


def write_plan(path: Path, jobs: list, repo: str, ref: str) -> None:
    body = [
        f"# {STAMP}",
        "name: plan",
        "on:",
        "  pull_request:",
        "    branches: [main, staging, production]",
        "permissions:",
        "  contents: read",
        "  id-token: write",
        "  pull-requests: write",
        "jobs:",
    ]
    ids = []
    for job_id, workflow, args in jobs:
        ids.append(job_id)
        body.append(workflow_call(job_id, workflow, repo, ref, {
            **args,
            "environment": "${{ github.base_ref == 'production' && 'prod' || 'staging' }}",
            "wif_provider": "${{ github.base_ref == 'production' && vars.WIF_PROVIDER_PROD || vars.WIF_PROVIDER_STAGING }}",
            "wif_service_account": "${{ github.base_ref == 'production' && vars.WIF_SERVICE_ACCOUNT_PROD || vars.WIF_SERVICE_ACCOUNT_STAGING }}",
            "pr_number": "${{ github.event.pull_request.number }}",
        }))
    body.append("  plan:")
    body.append(f"    needs: [{', '.join(ids)}]")
    body.append("    runs-on: ubuntu-latest")
    body.append("    steps:")
    body.append("      - run: echo plan passed")
    path.write_text("\n".join(body) + "\n")


def write_deploy(path: Path, branch: str, jobs: list, repo: str, ref: str) -> None:
    body = [
        f"# {STAMP}",
        f"name: deploy-{branch}",
        "on:",
        "  push:",
        f"    branches: [{branch}]",
        "permissions:",
        "  contents: read",
        "  id-token: write",
        "  pull-requests: write",
        "jobs:",
    ]
    for job_id, workflow, args in jobs:
        environment = args["environment"]
        suffix = "PROD" if environment == "prod" else "STAGING"
        body.append(workflow_call(job_id, workflow, repo, ref, {
            "environment": environment,
            "working_directory": args["working_directory"],
            "manifest": args["manifest"],
            "wif_provider": f"${{{{ vars.WIF_PROVIDER_{suffix} }}}}",
            "wif_service_account": f"${{{{ vars.WIF_SERVICE_ACCOUNT_{suffix} }}}}",
        }))
    path.write_text("\n".join(body) + "\n")


def write_readme(app: dict, components: list[dict], dest: Path) -> None:
    lines = [
        f"# {app['name']}",
        "",
        str(app["purpose"]).strip(),
        "",
        f"Production project: `{app['prod_project']}`. Region: `{app['region']}`.",
        "",
        "## Components",
        "",
    ]
    has_deploy = False
    local: list[str] = []
    tests: list[str] = []
    for component in components:
        name = component["name"]
        parts = set(component["parts"])
        lines.append(
            f"- `{name}` ({component['archetype']}, auth {component['auth']}, parts {', '.join(component['parts'])})"
        )
        root = f"components/{name}"
        if "api" in parts or "job" in parts or "worker" in parts:
            tests.append(f"cd {root} && uv run ruff check . && uv run pytest")
        if "ui" in parts:
            tests.append(f"cd {root}/frontend && npm run lint && npm run typecheck")
        if "api" in parts and "ui" in parts:
            local.append(
                f"cd {root}\n"
                "uv sync\n"
                "uv run uvicorn app.main:app --app-dir backend --reload --port 8000\n"
                "\n"
                f"cd {root}/frontend\n"
                "npm ci\n"
                "npm run dev"
            )
        elif "api" in parts:
            local.append(
                f"cd {root}\n"
                "uv sync\n"
                "uv run uvicorn app.main:app --app-dir backend --reload --port 8000"
            )
        elif "job" in parts or "worker" in parts:
            local.append(f"cd {root}\nuv sync\nuv run python -m app.main\nuv run pytest")
        if parts & {"api", "job", "worker"}:
            has_deploy = True
    lines += ["", "## Run locally", ""]
    if local:
        lines.append("```bash")
        lines.append("\n\n".join(local))
        lines.append("```")
    else:
        lines.append("This repo has no service to run. Change the files and open a pull request into `main`.")
    lines += ["", "## Tests", "", "```bash", "\n".join(tests) if tests else "No test command. Open a pull request into main.", "```"]
    lines += ["", "## Deploy", ""]
    if has_deploy:
        lines += [
            "`main` does not deploy. CI runs on the pull request.",
            "",
            "Push `main` onto `staging` to deploy staging. Open the URL the workflow comments.",
            "",
            "```bash",
            "git checkout staging",
            "git pull",
            "git merge main",
            "git push",
            "```",
            "",
            "Then open a pull request from `main` into `production` and merge it. That deploys production.",
            "",
        ]
    else:
        lines += ["This repo does not deploy. Merge pull requests into `main`.", ""]
    (dest / "README.md").write_text("\n".join(lines))


def generate(manifest_path: Path, dest: Path) -> None:
    app = load(manifest_path)
    errors = check(app)
    if errors:
        raise SystemExit("\n".join(errors))
    mapping = load(ROOT / "mapping.yaml")
    if dest.exists() and any(dest.iterdir()):
        raise SystemExit(f"{dest} is not empty")
    dest.mkdir(parents=True, exist_ok=True)
    shutil.copy2(manifest_path, dest / "service.yaml")
    (dest / "scripts").mkdir()
    shutil.copy2(ROOT / "scripts" / "render_tfvars.py", dest / "scripts" / "render_tfvars.py")
    _, rules = selected(mapping, app["components"])
    write_bundle(dest, rules)
    for component in app["components"]:
        comp_dir = dest / "components" / component["name"]
        copy_skeleton(mapping, component, comp_dir)
        write_component_manifest(app, component, comp_dir)
        write_infra(mapping, app, component, comp_dir)
    write_workflows(mapping, app["components"], dest)
    write_readme(app, app["components"], dest)
    pr = dest / ".github" / "pull_request_template.md"
    pr.write_text(
        "## Linear\n\n## What changed\n\n## OpenSpec\n\n"
        "Path, or none for a bug that did not need a design choice.\n\n"
        "## Commands run\n\n## Risk\n\n"
        "- [ ] This pull request does not mix product code with infra, workflows, or service.yaml\n"
    )


def main(argv: list[str]) -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("manifest", type=Path)
    parser.add_argument("dest", type=Path)
    args = parser.parse_args(argv[1:])
    generate(args.manifest, args.dest)
    print(args.dest)
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
