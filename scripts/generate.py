def _copy_missing_tree(src: Path, dest: Path) -> None:
    for item in src.rglob("*"):
        rel = item.relative_to(src)
        target = dest / rel
        if item.is_dir():
            target.mkdir(parents=True, exist_ok=True)
        elif not target.exists():
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(item, target)


def sync_runtime_sdk(component: dict, dest: Path, force: bool = False) -> None:
    """Keep shared runtime SDK files (`config.py`, `logging.py`) synced from `skeletons/_common`."""
    parts = set(component.get("parts", []))
    if not (parts & {"api", "job", "worker"}):
        return
    common_app = ROOT / "skeletons" / "_common" / "backend" / "app"
    target_app = dest / "backend" / "app"
    if not common_app.is_dir() or not target_app.is_dir():
        return
    for filename in ("config.py", "logging.py"):
        src_file = common_app / filename
        dst_file = target_app / filename
        if not src_file.is_file():
            continue
        if force or not dst_file.is_file():
            shutil.copy2(src_file, dst_file)
            continue
        existing = dst_file.read_text(errors="ignore")
        if (
            "generated by opptra/sdlc runtime-sdk" in existing
            or "Local-first environment and secret loader." in existing
            or "class JsonFormatter(logging.Formatter):" in existing
        ):
            shutil.copy2(src_file, dst_file)


def _ensure_pyproject_deps(pyproject: Path, packages: list[str]) -> None:
    text = pyproject.read_text()
    lines = text.splitlines()
    out: list[str] = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if line.strip() == "dependencies = []":
            out.append("dependencies = [")
            for pkg in packages:
                out.append(f'  "{pkg}",')
            out.append("]")
            i += 1
            continue
        if line.strip() == "dependencies = [":
            out.append(line)
            i += 1
            existing_block: list[str] = []
            while i < len(lines) and lines[i].strip() != "]":
                existing_block.append(lines[i])
                i += 1
            existing_joined = "\n".join(existing_block)
            out.extend(existing_block)
            for pkg in packages:
                pkg_name = pkg.split(">=")[0].split("[")[0]
                if pkg_name not in existing_joined:
                    out.append(f'  "{pkg}",')
            if i < len(lines):
                out.append(lines[i])
                i += 1
            continue
        out.append(line)
        i += 1
    pyproject.write_text("\n".join(out) + "\n")


