def workflow_call(
    job_id: str,
    workflow: str,
    repo: str,
    ref: str,
    arguments: dict[str, str],
    condition: str | None = None,
) -> str:
    lines = [f"  {job_id}:"]
    if condition:
        lines.append(f"    if: {condition}")
    lines.append(f"    uses: {repo}/.github/workflows/{workflow}@{ref}")
    if arguments:
        lines.append("    with:")
        for key, value in arguments.items():
            lines.append(f"      {key}: {value}")
    return "\n".join(lines)


def write_workflows(mapping: dict, components: list[dict], dest: Path, include_deploy: bool = True) -> None:
    ref = mapping["ref"]
    workflows = dest / ".github" / "workflows"
    workflows.mkdir(parents=True, exist_ok=True)
    ci_jobs = []
    seen_ci_targets: set[tuple[str, str]] = set()
    plan_jobs = []
    deploy_staging = []
    deploy_production = []
    for component in components:
        caps, _ = selected(mapping, [component])
        base = component["name"]
        comp_path = str(component.get("path") or f"components/{base}")
        fe_path = str(
            component.get("frontend_path")
            or (f"{comp_path}/frontend" if comp_path != "." else "frontend")
        )
        manifest_rel = (
            f"{comp_path}/service.yaml" if comp_path != "." else "service.yaml"
        )
        for capability in caps:
            spec = mapping["capabilities"][capability]
            directory = spec["directory"]
            if directory == "component":
                path = comp_path
            elif directory == "frontend":
                path = fe_path
            else:
                path = "."
            job_id = f"{capability}-{base}".replace("_", "-")
            args = {"working_directory": path} if directory != "repo" else {}
            if capability in {"terraform-plan", "deploy-cloud-run", "deploy-job", "deploy-worker"}:
                args["manifest"] = manifest_rel
            if capability == "terraform-plan":
                if include_deploy:
                    plan_jobs.append((job_id, spec["workflow"], args))
            elif capability.startswith("deploy-"):
                if include_deploy:
                    if component.get("docker_context"):
                        args["docker_context"] = str(component["docker_context"])
                    if component.get("dockerfile"):
                        args["dockerfile"] = str(component["dockerfile"])
                    deploy_staging.append(
                        (job_id, spec["workflow"], {**args, "environment": "staging"})
                    )
                    deploy_production.append(
                        (job_id, spec["workflow"], {**args, "environment": "prod"})
                    )
            else:
                target_key = (spec["workflow"], path)
                if target_key not in seen_ci_targets:
                    seen_ci_targets.add(target_key)
                    if path == ".":
                        job_id = capability.replace("_", "-")
                    if capability == "python-ci" and component.get("run_tests") is False:
                        args = {**args, "run_tests": "false"}
                    ci_jobs.append((job_id, spec["workflow"], args))
    repo = mapping["repo"]
    write_gate(
        workflows / "ci.yml",
        "ci",
        ci_jobs,
        repo,
        ref,
        """on:
  pull_request:
""",
    )
    if plan_jobs:
        write_plan(workflows / "plan.yml", plan_jobs, repo, ref)
    if deploy_staging:
        write_deploy(workflows / "deploy-staging.yml", "staging", deploy_staging, repo, ref)
        write_deploy(workflows / "deploy-production.yml", "production", deploy_production, repo, ref)


def write_gate(path: Path, name: str, jobs: list, repo: str, ref: str, trigger: str) -> None:
    body = [f"# {STAMP}", f"name: {name}", trigger, "permissions:", "  contents: read", "jobs:"]
    ids = []
    for job_id, workflow, args in jobs:
        ids.append(job_id)
        body.append(workflow_call(job_id, workflow, repo, ref, args))
    needs = ", ".join(ids) if ids else ""
    body.append("  ci:")
    if needs:
        body.append(f"    needs: [{needs}]")
    body.append("    runs-on: ubuntu-latest")
    body.append("    steps:")
    body.append("      - run: echo capabilities passed")
    path.write_text("\n".join(body) + "\n")


def write_plan(path: Path, jobs: list, repo: str, ref: str) -> None:
    body = [
        f"# {STAMP}",
        "name: plan",
        "on:",
        "  pull_request:",
        "    branches: [main, staging, production]",
        "permissions:",
        "  contents: read",
        "  id-token: write",
        "  pull-requests: write",
        "jobs:",
    ]
    ids = []
    for job_id, workflow, args in jobs:
        ids.append(job_id)
        body.append(
            workflow_call(
                job_id,
                workflow,
                repo,
                ref,
                {
                    **args,
                    "environment": "${{ github.base_ref == 'production' && 'prod' || 'staging' }}",
                    "wif_provider": "${{ github.base_ref == 'production' && vars.WIF_PROVIDER_PROD || vars.WIF_PROVIDER_STAGING }}",
                    "wif_service_account": "${{ github.base_ref == 'production' && vars.WIF_SERVICE_ACCOUNT_PROD || vars.WIF_SERVICE_ACCOUNT_STAGING }}",
                    "pr_number": "${{ github.event.pull_request.number }}",
                },
            )
        )
    body.append("  plan:")
    body.append(f"    needs: [{', '.join(ids)}]")
    body.append("    runs-on: ubuntu-latest")
    body.append("    steps:")
    body.append("      - run: echo plan passed")
    path.write_text("\n".join(body) + "\n")


def write_deploy(path: Path, branch: str, jobs: list, repo: str, ref: str) -> None:
    body = [
        f"# {STAMP}",
        f"name: deploy-{branch}",
        "on:",
        "  push:",
        f"    branches: [{branch}]",
        "  workflow_dispatch:",
        "permissions:",
        "  contents: read",
        "  id-token: write",
        "  pull-requests: write",
        "jobs:",
    ]
    for job_id, workflow, args in jobs:
        environment = args["environment"]
        suffix = "PROD" if environment == "prod" else "STAGING"
        call_args = {
            "environment": environment,
            "working_directory": args["working_directory"],
            "manifest": args["manifest"],
        }
        if args.get("docker_context"):
            call_args["docker_context"] = args["docker_context"]
        if args.get("dockerfile"):
            call_args["dockerfile"] = args["dockerfile"]
        call_args["wif_provider"] = f"${{{{ vars.WIF_PROVIDER_{suffix} }}}}"
        call_args["wif_service_account"] = f"${{{{ vars.WIF_SERVICE_ACCOUNT_{suffix} }}}}"
        body.append(
            workflow_call(
                job_id,
                workflow,
                repo,
                ref,
                call_args,
                condition=f"github.ref == 'refs/heads/{branch}'",
            )
        )
    path.write_text("\n".join(body) + "\n")


